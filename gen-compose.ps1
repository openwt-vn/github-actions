# Read RUNNER_COUNT from .env and write docker-compose.yml with one service per runner.
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$envPath = Join-Path $root '.env'
$composePath = Join-Path $root 'docker-compose.yml'

if (-not (Test-Path -LiteralPath $envPath)) {
    throw ".env not found at $envPath"
}

$vars = @{}
Get-Content -LiteralPath $envPath | ForEach-Object {
    $line = $_.Trim()
    if ($line -eq '' -or $line.StartsWith('#')) {
        return
    }
    if ($line.StartsWith('export ')) {
        $line = $line.Substring(7).Trim()
    }
    $idx = $line.IndexOf('=')
    if ($idx -lt 1) {
        return
    }
    $key = $line.Substring(0, $idx).Trim()
    $value = $line.Substring($idx + 1).Trim()
    if (($value.StartsWith('"') -and $value.EndsWith('"')) -or ($value.StartsWith("'") -and $value.EndsWith("'"))) {
        $value = $value.Substring(1, $value.Length - 2)
    }
    $vars[$key] = $value
}

$countText = $vars['RUNNER_COUNT']
if ($countText -notmatch '^[1-9][0-9]*$') {
    throw 'RUNNER_COUNT must be a positive integer in .env'
}
$count = [int]$countText

$prefix = $vars['RUNNER_NAME_PREFIX']
if ([string]::IsNullOrWhiteSpace($prefix)) {
    $prefix = 'runner'
}
if ($prefix -notmatch '^[A-Za-z0-9][A-Za-z0-9_-]*$') {
    throw 'RUNNER_NAME_PREFIX may contain only letters, digits, underscores, and hyphens'
}

$scope = $vars['RUNNER_SCOPE']
if ([string]::IsNullOrWhiteSpace($scope)) {
    $scope = 'repo'
}
if ($scope -eq 'org' -and [string]::IsNullOrWhiteSpace($vars['ORG_NAME'])) {
    Write-Warning 'RUNNER_SCOPE=org but ORG_NAME is empty. Fill ORG_NAME before starting the containers.'
}
if ($scope -eq 'repo' -and [string]::IsNullOrWhiteSpace($vars['REPO_URL'])) {
    Write-Warning 'RUNNER_SCOPE=repo but REPO_URL is empty. Fill REPO_URL before starting the containers.'
}

$yaml = New-Object System.Text.StringBuilder
[void]$yaml.AppendLine('# Generated by gen-compose.cmd from .env. Do not edit by hand.')
[void]$yaml.AppendLine('services:')

$names = @()
for ($i = 1; $i -le $count; $i++) {
    $runnerName = "$prefix-$i"
    $names += $runnerName
    $service = "github-runner-$i"

    New-Item -ItemType Directory -Force -Path (Join-Path $root "runner-data\$i") | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $root "work\$i") | Out-Null

    [void]$yaml.AppendLine("  ${service}:")
    [void]$yaml.AppendLine('    image: myoung34/github-runner:latest')
    [void]$yaml.AppendLine("    container_name: $service")
    [void]$yaml.AppendLine('    restart: unless-stopped')
    [void]$yaml.AppendLine('    env_file:')
    [void]$yaml.AppendLine('      - .env')
    [void]$yaml.AppendLine('    environment:')
    [void]$yaml.AppendLine("      RUNNER_NAME: $runnerName")
    [void]$yaml.AppendLine('      RUNNER_WORKDIR: /tmp/runner/work')
    [void]$yaml.AppendLine('      CONFIGURED_ACTIONS_RUNNER_FILES_DIR: /runner/data')
    # Persistence requires this. Otherwise the image exits on startup.
    [void]$yaml.AppendLine('      DISABLE_AUTOMATIC_DEREGISTRATION: "true"')
    [void]$yaml.AppendLine('      UNSET_CONFIG_VARS: "true"')
    [void]$yaml.AppendLine('    volumes:')
    [void]$yaml.AppendLine('      - /var/run/docker.sock:/var/run/docker.sock')
    [void]$yaml.AppendLine("      - ./runner-data/${i}:/runner/data")
    [void]$yaml.AppendLine("      - ./work/${i}:/tmp/runner")
}

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($composePath, $yaml.ToString(), $utf8)

Write-Output ("Wrote {0} with {1} runner(s): {2}" -f $composePath, $count, ($names -join ', '))
Write-Output 'Start with: docker compose up -d --remove-orphans'
if ($count -gt 1) {
    Write-Output 'Each runner has its own name, runner-data directory, and work directory.'
}
