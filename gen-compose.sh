#!/bin/sh
# Read RUNNER_COUNT from .env and write docker-compose.yml with one service per runner.
set -eu

root=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
env_file="$root/.env"
compose_file="$root/docker-compose.yml"

if [ ! -f "$env_file" ]; then
    echo ".env not found at $env_file" >&2
    exit 1
fi

# Print the last value assigned to a key. Ignores comments and blank lines.
get_value() {
    awk -v key="$1" '
        {
            line = $0
            sub(/\r$/, "", line)
            if (line ~ /^[[:space:]]*#/ || line ~ /^[[:space:]]*$/) {
                next
            }
            sub(/^[[:space:]]+/, "", line)
            sub(/^export[[:space:]]+/, "", line)
            eq = index(line, "=")
            if (eq <= 1) {
                next
            }
            k = substr(line, 1, eq - 1)
            gsub(/[[:space:]]/, "", k)
            if (k != key) {
                next
            }
            v = substr(line, eq + 1)
            sub(/^[[:space:]]+/, "", v)
            sub(/[[:space:]]+$/, "", v)
            first = substr(v, 1, 1)
            last = substr(v, length(v), 1)
            if ((first == "\"" && last == "\"") || (first == "'" && last == "'")) {
                v = substr(v, 2, length(v) - 2)
            }
            value = v
        }
        END {
            print value
        }
    ' "$env_file"
}

count=$(get_value RUNNER_COUNT)
case "$count" in
    ''|*[!0-9]*)
        echo 'RUNNER_COUNT must be a positive integer in .env' >&2
        exit 1
        ;;
esac
if [ "$count" -lt 1 ]; then
    echo 'RUNNER_COUNT must be a positive integer in .env' >&2
    exit 1
fi

prefix=$(get_value RUNNER_NAME_PREFIX)
if [ -z "$prefix" ]; then
    prefix=runner
fi
case "$prefix" in
    *[!A-Za-z0-9_-]*|[!A-Za-z0-9]*)
        echo 'RUNNER_NAME_PREFIX may contain only letters, digits, underscores, and hyphens' >&2
        exit 1
        ;;
esac

scope=$(get_value RUNNER_SCOPE)
if [ -z "$scope" ]; then
    scope=repo
fi
org_name=$(get_value ORG_NAME)
repo_url=$(get_value REPO_URL)
if [ "$scope" = org ] && [ -z "$org_name" ]; then
    echo 'Warning: RUNNER_SCOPE=org but ORG_NAME is empty. Fill ORG_NAME before starting the containers.' >&2
fi
if [ "$scope" = repo ] && [ -z "$repo_url" ]; then
    echo 'Warning: RUNNER_SCOPE=repo but REPO_URL is empty. Fill REPO_URL before starting the containers.' >&2
fi

tmp=$(mktemp)
# shellcheck disable=SC2064
trap "rm -f '$tmp'" EXIT

printf '%s\n' '# Generated by gen-compose.cmd from .env. Do not edit by hand.' 'services:' > "$tmp"

names=
i=1
while [ "$i" -le "$count" ]; do
    runner_name="${prefix}-${i}"
    service="github-runner-${i}"
    if [ -z "$names" ]; then
        names=$runner_name
    else
        names="$names, $runner_name"
    fi

    mkdir -p "$root/runner-data/$i" "$root/work/$i"

    cat >> "$tmp" <<EOF
  ${service}:
    image: myoung34/github-runner:latest
    container_name: ${service}
    restart: unless-stopped
    env_file:
      - .env
    environment:
      RUNNER_NAME: ${runner_name}
      RUNNER_WORKDIR: /tmp/runner/work
      CONFIGURED_ACTIONS_RUNNER_FILES_DIR: /runner/data
      DISABLE_AUTOMATIC_DEREGISTRATION: "true"
      UNSET_CONFIG_VARS: "true"
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - ./runner-data/${i}:/runner/data
      - ./work/${i}:/tmp/runner
EOF
    i=$((i + 1))
done

mv "$tmp" "$compose_file"
trap - EXIT

echo "Wrote $compose_file with $count runner(s): $names"
echo 'Start with: docker compose up -d --remove-orphans'
if [ "$count" -gt 1 ]; then
    echo 'Each runner has its own name, runner-data directory, and work directory.'
fi
